HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
import arbiter as ar          # noqa: E402

DEST = {"allies": Path.home() / "Desktop" / "料鋒_Run7_藍軍指揮部",
        "axis": Path.home() / ".acies" / "run7_red_hq"}
ZH = {"allies": "藍軍", "axis": "紅軍"}

s = ar.load(HERE / "final_state.json")
sc = ar.score(s)


def tick_scores():
    """逐 tick 的計分推移，自各快照重算。"""
    rows = []
    for n in range(1, 9):
        f = HERE / f"snap_T{n}start.json"
        if not f.exists():
            continue
        st = ar.load(f)
        c = ar.score(st)
        rows.append((n - 1, c["allies"]["points"], c["axis"]["points"]))
    rows.append((8, sc["allies"]["points"], sc["axis"]["points"]))
    return rows


def loss_table(side):
    out = ["| 編隊 | 終局位置 | 兵力 | 人員損失 | 戰車損失 | 火砲損失 | 狀態 |",
           "|---|---|---:|---:|---:|---:|---|"]
    for uid, u in sorted(ar.own(s, side).items()):
        l = u["losses"]
        out.append(f"| {uid} | {tuple(u['pos'])} | {u.get('personnel',0):,} "
                   f"| {l['personnel']:,} | {l['tanks']} | {l['guns']} "
                   f"| {ar.status_of(u)} |")
    return "\n".join(out)


