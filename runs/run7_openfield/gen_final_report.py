def render(side):
    rows = "\n".join(f"| T{n} | {a} | {x} |" for n, a, x in tick_scores())
    return TPL.format(
        A_INF=sc["allies"]["inflicted"], X_INF=sc["axis"]["inflicted"],
        A_PTS=sc["allies"]["points"], X_PTS=sc["axis"]["points"],
        WINNER=("**藍軍勝**" if sc["allies"]["points"] > sc["axis"]["points"]
                else "**紅軍勝**" if sc["axis"]["points"] > sc["allies"]["points"]
                else "**平手**"),
        MARGIN=("" if sc["allies"]["points"] == sc["axis"]["points"]
                else f"，差 {abs(sc['allies']['points'] - sc['axis']['points'])} 分。"),
        TICKS="每列為該 tick **結束時**的累計分數。\n\n"
              "| tick | 藍軍累計 | 紅軍累計 |\n|---|---:|---:|\n" + rows,
        A_TAB=loss_table("allies"), X_TAB=loss_table("axis"),
        ZH_SELF=ZH[side])


def norm(t):
    for a, b in (("藍", "§"), ("紅", "§"), ("BLU", "¤"), ("RED", "¤")):
        t = t.replace(a, b)
    return t


out = {}
for side, d in DEST.items():
    d.mkdir(parents=True, exist_ok=True)
    txt = render(side)
    (d / "終局戰報.md").write_text(txt)
    out[side] = txt
    print(f"  {ZH[side]} → {d / '終局戰報.md'}（{len(txt.splitlines())} 行）")

if norm(out["allies"]) == norm(out["axis"]):
    print("\n✅ 兩份終局戰報正規化後逐位元組相同")
else:
    import difflib
    d = [l for l in difflib.unified_diff(norm(out["allies"]).split("\n"),
                                         norm(out["axis"]).split("\n"), lineterm="", n=0)
         if l[:1] in "+-" and l[:3] not in ("+++", "---")]
    print(f"\n❌ 有 {len(d)} 行差異：" + " / ".join(x[:70] for x in d[:5]))
    sys.exit(1)
