def normalise(text):
    """把陣營字樣正規化，用於驗證兩份手冊除此之外逐位元組相同。"""
    for a, b in (("藍", "§"), ("紅", "§"), ("BLU", "¤"), ("RED", "¤"),
                 ("allies", "★"), ("axis", "★"),
                 ("西緣 x=0", "◇"), ("東緣 x=29", "◇")):
        text = text.replace(a, b)
    return text


