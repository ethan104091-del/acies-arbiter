#!/usr/bin/env python3
"""洩密補救：把雙方日誌裡「由裁判洩漏取得」的敵情段落切除，原檔留存 discarded/。
保留：各自自己的部隊狀態、自己的構想、劇本公開的開局鏡像部署推論。
切除：敵方 T0 逐時位置、敵方主指揮所位置、敵方拆營資訊，及由其直接推得的結論。
"""
import shutil, re
from pathlib import Path

SP = Path(__file__).parent
DISC = SP / "discarded"
DISC.mkdir(exist_ok=True)
RED = Path.home() / "Desktop" / "料鋒_紅軍指揮部"
BLUE = SP / "blue_hq"

STAMP = """
> ═══ 裁判勘誤（{when}）═══
> 上一版戰報的第七節因裁判程式的 bug，誤把**上帝視角逐小時日誌**送給雙方，
> 內容包含對方每個單位的精確座標與**雙方主指揮所位置**。這不是任何一方偵察得來的。
> 依對局裁定：**該批情報全部作廢**，本段落以下的敵情推論已由裁判切除，Tick 1 命令重下。
> 你在 Tick 1 之前對敵方的合法認知只有：劇本公開的「開局 180° 鏡像部署」及由此的推論。
> bug 已修正——之後戰報只會給你「你自己的動作」＋「你當時真正偵獲到的敵情」。
> ═════════════════════════
"""

# ── 留存原檔 ──
for src in (RED / "紅軍作戰日誌.md", RED / "命令_T1.md",
            BLUE / "藍軍作戰日誌.md", BLUE / "命令_T1.md"):
    if src.exists():
        shutil.copy2(src, DISC / f"洩漏版_{src.name}")

# ── 紅軍日誌：切掉 Tick 1 情報更新段的洩漏行 ──
p = RED / "紅軍作戰日誌.md"
t = p.read_text()
t = t.split("## Tick 1 檢討與情報更新")[0]
t += """## Tick 1 檢討（12:00）— 裁判勘誤後重寫
- 主指揮所已於 global hour 2 在 (29,8) 完成，軍長進駐；後續單位命令延遲為 +1。
- 我軍先遣已開始前推但**仍未與敵接觸**：RED-3 (26,3)、RED-2 (26,8)、RED-1 (26,13)、RED-AD (24,9)、RED-SF (24,15)，疲勞均 15、補給完整。
- 裁判裁量通報：RED-AD 原目標 (24,8) 為森林格、戰車不可入，已依命令意圖繞南停於 (24,9)（緊鄰原目標）。
- **敵情：零。** 本 tick 我方沒有任何一個單位偵獲到敵軍（我方無偵察營在外，師級視距僅 3 格）。
  對敵的合法認知僅限：劇本公開的開局 180° 鏡像部署，以及由此的推論。
""" + STAMP.format(when="Tick 1 開始前")
p.write_text(t)
print("✅ 紅軍日誌已淨化")

# ── 藍軍日誌：切掉「敵軍最後已知位置紀錄表」與「T1 重大情報」兩段 ──
p = BLUE / "藍軍作戰日誌.md"
t = p.read_text()
head, _, rest = t.partition("### 敵軍最後已知位置紀錄表")
_, _, tail = rest.partition("## 2b. 修正後的核心算式")
t = head + """### 敵軍最後已知位置紀錄表
| 編隊 | 最後位置 | 時間 | 備註 |
|---|---|---|---|
| RED-1 | (28,13) | T0 gh0 | 劇本開局鏡像事實 |
| RED-2 | (28,8) | T0 gh0 | 同 |
| RED-3 | (28,3) | T0 gh0 | 同 |
| RED-AD | (27,8) | T0 gh0 | 同 |
| RED-SF | (27,15) | T0 gh0 | 同；預期沿南緣西進 |

**T1 敵情：零。** 我的四個偵察營都還在 x=3-6，最東 (6,8)，沒有任何一個單位偵獲到敵軍。
敵主力現在在哪、敵主指揮所在哪，**我不知道**。
""" + STAMP.format(when="Tick 1 開始前") + "\n## 2b. 修正後的核心算式" + tail
p.write_text(t)
print("✅ 藍軍日誌已淨化")

for f in (RED / "命令_T1.md", BLUE / "命令_T1.md"):
    if f.exists():
        f.unlink()
        print("🗑  作廢", f.name)
