def sec(text, head, level="## "):
    """自 `## head` 起到下一個同級標題前（含子標題）；去掉尾端分隔線。"""
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith(level + head))
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith(level)), len(lines))
    body = lines[start:end]
    while body and body[-1].strip() in ("", "---"):
        body.pop()
    return "\n".join(body) + "\n"


def retitle(block, new_title):
    """換掉段落第一行標題。"""
    lines = block.splitlines()
    lines[0] = new_title
    return "\n".join(lines) + "\n"


def note(text):
    return "> " + text.replace("\n", "\n> ") + "\n"


